function New-ParityConsumerProbeDispatcherContent {
  <#
  .SYNOPSIS
    Builds the version-independent dispatcher script text for one consumer probe task.

  .DESCRIPTION
    The scheduled task's action always runs the same dispatcher path; the dispatcher names the
    installed module version's scripts\Invoke-ParityConsumerProbeTask.ps1. A version repoint
    rewrites only this file and never touches Task Scheduler (the design of
    Register-ATAPParityScheduledTasks). The task script is dual-purpose and runs only under
    `pwsh -File`, so the dispatcher reproduces exactly that invocation, one process deeper.
    PowerShell profiles load (no -NoProfile), by operator decision 2026-11-15 ("I would rather not
    start any tasks without the profile"), so $global:settings and the ATAP profile environment
    are present for the task identity.

  .PARAMETER ModuleVersion
    Module version recorded in the header.

  .PARAMETER ScriptPath
    Fully qualified path to the installed Invoke-ParityConsumerProbeTask.ps1.

  .PARAMETER LogicalIdentity
    Consumer LogicalIdentity passed to the task script.

  .PARAMETER PolicyPath
    Policy path passed to the task script.

  .PARAMETER StatePath
    ParityState root passed to the task script.

  .PARAMETER PwshPath
    Fully qualified pwsh.exe path.

  .OUTPUTS
    String.
  #>
  [CmdletBinding()]
  [OutputType([string])]
  param(
    [Parameter(Mandatory = $true)] [string] $ModuleVersion,
    [Parameter(Mandatory = $true)] [string] $ScriptPath,
    [Parameter(Mandatory = $true)] [string] $LogicalIdentity,
    [Parameter(Mandatory = $true)] [string] $PolicyPath,
    [Parameter(Mandatory = $true)] [string] $StatePath,
    [Parameter(Mandatory = $true)] [string] $PwshPath
  )

  begin {
  }

  process {
    foreach ($path in @($ScriptPath, $PolicyPath, $StatePath, $PwshPath)) {
      if (-not [IO.Path]::IsPathFullyQualified($path)) { throw "Dispatcher path '$path' must be fully qualified." }
    }
    if ($LogicalIdentity -notmatch '^[A-Za-z0-9_.-]+$') {
      throw "LogicalIdentity '$LogicalIdentity' may contain only letters, digits, '_', '.', and '-'."
    }
    $quote = { param([string] $Value) "'" + ($Value -replace "'", "''") + "'" }
    @(
      "# Generated by Register-ParityConsumerProbeTasks for SystemParityMonitor $ModuleVersion. Do not edit by hand."
      '# Rewriting this file is how a consumer probe version repoint happens; the scheduled task'
      '# definition is immutable and intentionally never references a version.'
      '#'
      '# The task script must be launched with -File. It carries an &-proof dual-purpose guard and'
      '# does nothing at all when invoked with the call operator or dot-sourced.'
      "`$ErrorActionPreference = 'Stop'"
      ("& {0} -NonInteractive -ExecutionPolicy Bypass -File {1} -LogicalIdentity {2} -PolicyPath {3} -StatePath {4}" -f (& $quote $PwshPath), (& $quote $ScriptPath), (& $quote $LogicalIdentity), (& $quote $PolicyPath), (& $quote $StatePath))
      'exit $LASTEXITCODE'
    ) -join "`n"
  }

  end {
  }
}
